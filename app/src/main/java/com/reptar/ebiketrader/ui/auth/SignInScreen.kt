@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SignInScreen(
    authViewModel: AuthViewModel,
    onBack: () -> Unit,
    onSignedIn: () -> Unit,
) {
    val state by authViewModel.state.collectAsStateWithLifecycle()
    val context = LocalContext.current

    var isCreating by remember { mutableStateOf(false) }
    var name by remember { mutableStateOf("") }
    var email by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var passwordVisible by remember { mutableStateOf(false) }

    // The screen dismisses itself the moment Firebase reports a session,
    // whichever provider got us there.
    LaunchedEffect(state.isSignedIn) { if (state.isSignedIn) onSignedIn() }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(if (isCreating) "Create an account" else "Sign in") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
            )
        },
    ) { insets ->
        Column(
            Modifier
                .fillMaxSize()
                .padding(insets)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 24.dp, vertical = 16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            // Same header as SignInView on iOS: the mark at 40/26, with the
            // reason for the account underneath it.
            Column(
                modifier = Modifier.fillMaxWidth().padding(top = 12.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
                verticalArrangement = Arrangement.spacedBy(6.dp),
            ) {
                Wordmark(badgeSize = 40.dp, fontSize = 26.sp)
                Text(
                    "Save listings, message sellers, and list your own bike.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    textAlign = TextAlign.Center,
                )
            }

            OutlinedButton(
                onClick = {
                    // default_web_client_id is generated by the google-services
                    // plugin from the type-3 OAuth client in
                    // google-services.json, so the web client id is never
                    // hardcoded here and never drifts from the Firebase config.
                    authViewModel.signInWithGoogle(
                        context = context,
                        serverClientId = context.getString(R.string.default_web_client_id),
                    )
                },
                enabled = !state.isWorking,
                modifier = Modifier.fillMaxWidth(),
            ) { Text("Continue with Google") }

            HorizontalDivider(Modifier.padding(vertical = 4.dp))

            if (isCreating) {
                OutlinedTextField(
                    value = name,
                    onValueChange = { name = it },
                    label = { Text("Your name") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                )
            }

            OutlinedTextField(
                value = email,
                onValueChange = { email = it },
                label = { Text("Email") },
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )

            OutlinedTextField(
                value = password,
                onValueChange = { password = it },
                label = { Text("Password") },
                visualTransformation = if (passwordVisible) {
                    VisualTransformation.None
                } else {
                    PasswordVisualTransformation()
                },
                trailingIcon = {
                    IconButton(onClick = { passwordVisible = !passwordVisible }) {
                        Icon(
                            if (passwordVisible) Icons.Filled.VisibilityOff else Icons.Filled.Visibility,
                            contentDescription = if (passwordVisible) "Hide password" else "Show password",
                        )
                    }
                },
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )

            state.errorMessage?.let { message ->
                Text(
                    message,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.error,
                )
            }

            Button(
                onClick = {
                    if (isCreating) {
                        authViewModel.signUp(email, password, name)
                    } else {
                        authViewModel.signIn(email, password)
                    }
                },
                enabled = !state.isWorking && email.isNotBlank() && password.isNotBlank(),
                modifier = Modifier.fillMaxWidth(),
            ) {
                if (state.isWorking) {
                    CircularProgressIndicator(Modifier.padding(2.dp), strokeWidth = 2.dp)
                } else {
                    Text(if (isCreating) "Create account" else "Sign in")
                }
            }

            TextButton(
                onClick = {
                    isCreating = !isCreating
                    authViewModel.clearError()
                },
                modifier = Modifier.fillMaxWidth(),
            ) {
                Text(
                    if (isCreating) {
                        "Already have an account? Sign in"
                    } else {
                        "New here? Create an account"
                    }
                )
            }

            if (!isCreating) {
                TextButton(
                    onClick = { authViewModel.sendPasswordReset(email) },
                    enabled = !state.isWorking && email.isNotBlank(),
                    modifier = Modifier.fillMaxWidth(),
                ) { Text("Forgot your password?") }
            }
        }
    }
}
